# --------------------------------------------------------------------------------------------- sounds

RATE = 44100


def env(n: int, attack: float, decay: float) -> np.ndarray:
    t = np.arange(n) / RATE
    a = np.clip(t / max(attack, 1e-4), 0, 1)
    return a * np.exp(-t / decay)


def sweep(f0: float, f1: float, n: int, curve: float = 1.0) -> np.ndarray:
    """Phase of a tone gliding from f0 to f1 (exponential glide)."""
    t = np.linspace(0, 1, n) ** curve
    freq = f0 * (f1 / f0) ** t
    return 2 * np.pi * np.cumsum(freq) / RATE


def bandpass_noise(rng, n: int, centre: np.ndarray, q: float = 4.0) -> np.ndarray:
    """White noise through a time-varying resonant band-pass (state-variable filter)."""
    noise = rng.standard_normal(n)
    out = np.zeros(n)
    low = band = 0.0
    damp = 1.0 / q
    for i in range(n):
        f = 2 * math.sin(math.pi * min(centre[i], RATE / 6) / RATE)
        high = noise[i] - low - damp * band
        band += f * high
        low += f * band
        out[i] = band
    return out


def finish(x: np.ndarray, peak: float = 0.8) -> np.ndarray:
    fade = min(len(x), int(0.01 * RATE))
    x = x.copy()
    x[-fade:] *= np.linspace(1, 0, fade)
    return x / (np.max(np.abs(x)) + 1e-9) * peak


def snd_fire(f0: float, f1: float, seed: int) -> np.ndarray:
    rng = np.random.default_rng(seed)
    n = int(0.42 * RATE)
    ph = sweep(f0, f1, n, 0.6)
    tone = np.sin(ph + 1.8 * np.sin(ph * 0.5)) * env(n, 0.003, 0.11)
    zap = np.sign(np.sin(ph * 1.5)) * env(n, 0.002, 0.03) * 0.25
    thump = np.sin(sweep(160, 60, n)) * env(n, 0.002, 0.06) * 0.9
    hiss = bandpass_noise(rng, n, np.linspace(5000, 1500, n), 2.0) * env(n, 0.001, 0.04) * 0.15
    return finish(tone + zap + thump + hiss)


def snd_open() -> np.ndarray:
    rng = np.random.default_rng(3)
    n = int(0.9 * RATE)
    t = np.arange(n) / RATE
    swell = np.sin(np.pi * np.clip(t / 0.9, 0, 1)) ** 1.5
    whoosh = bandpass_noise(rng, n, 300 * (6 ** (t / 0.9)), 6.0) * swell * 0.35
    hum = (np.sin(sweep(110, 220, n)) + 0.5 * np.sin(sweep(220, 440, n) * 1.01)) * swell * (1 + 0.2 * np.sin(2 * np.pi * 7 * t))
    shimmer = np.sin(sweep(1800, 2600, n)) * np.sin(2 * np.pi * 13 * t) ** 2 * swell * 0.12
    return finish(whoosh + 0.5 * hum + shimmer, 0.75)


def snd_close() -> np.ndarray:
    rng = np.random.default_rng(4)
    n = int(0.5 * RATE)
    t = np.arange(n) / RATE
    e = env(n, 0.01, 0.14)
    tone = np.sin(sweep(900, 140, n, 0.7)) * e
    suck = bandpass_noise(rng, n, 2500 * (0.15 ** (t / 0.5)), 5.0) * e * 0.5
    pop = np.sin(2 * np.pi * 90 * t) * env(n, 0.002, 0.03) * np.clip((t - 0.38) * 100, 0, 1)
    return finish(tone + suck + pop, 0.7)


def snd_fizzle() -> np.ndarray:
    rng = np.random.default_rng(5)
    n = int(0.55 * RATE)
    t = np.arange(n) / RATE
    crackle = (rng.random(n) < 0.012 * np.exp(-t / 0.2)) * rng.uniform(-1, 1, n)
    crackle = np.convolve(crackle, np.exp(-np.arange(200) / 30), mode="same")
    tone = np.sin(sweep(620, 180, n)) * env(n, 0.003, 0.09) * 0.6
    hiss = bandpass_noise(rng, n, np.full(n, 3500.0), 1.5) * env(n, 0.002, 0.12) * 0.3
    return finish(crackle * 0.8 + tone + hiss, 0.7)


def snd_enter() -> np.ndarray:
    rng = np.random.default_rng(6)
    n = int(0.6 * RATE)
    t = np.arange(n) / RATE
    shape = np.sin(np.pi * np.clip(t / 0.6, 0, 1)) ** 2
    vw = np.sin(sweep(180, 760, n, 1.3)) + 0.6 * np.sin(sweep(185, 770, n, 1.3) * 1.5)
    air = bandpass_noise(rng, n, 600 + 2600 * np.sin(np.pi * t / 0.6), 3.0) * 0.4
    return finish((vw * 0.6 + air) * shape, 0.7)


def snd_denied() -> np.ndarray:
    n = int(0.11 * RATE)
    beep = lambda f: np.sign(np.sin(2 * np.pi * f * np.arange(n) / RATE)) * 0.25 + np.sin(2 * np.pi * f * np.arange(n) / RATE)
    e = env(n, 0.004, 0.05)
    return finish(np.concatenate([beep(520) * e, np.zeros(int(0.03 * RATE)), beep(390) * e]), 0.45)


def write_ogg(samples: np.ndarray, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        wav = Path(tmp) / "x.wav"
        with wave.open(str(wav), "wb") as w:
            w.setnchannels(1)
            w.setsampwidth(2)
            w.setframerate(RATE)
            w.writeframes((np.clip(samples, -1, 1) * 32767).astype("<i2").tobytes())
        subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-i", str(wav), "-c:a", "libvorbis", "-q:a", "4",
                        "-fflags", "+bitexact", "-flags:a", "+bitexact", "-map_metadata", "-1", str(path)],
                       check=True)
    print(f"  {path.relative_to(ROOT)}  {len(samples) / RATE:.2f}s")


