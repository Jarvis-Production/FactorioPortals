def make_docs() -> None:
    """README previews built from the shipped sheets: the two portals swirling on a grass-coloured ground."""
    media = ROOT / "docs" / "media"
    media.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(0)
    w, h = 2 * PORTAL_SIZE, PORTAL_SIZE
    noise = np.kron(rng.normal(0, 1, (h // 4, w // 4)), np.ones((4, 4)))
    ground = np.clip(np.array([78, 84, 44]) / 255 * (1 + 0.1 * noise[..., None]), 0, 1)
    ground_img = rgba(ground, np.ones((h, w)))
    frames = []
    for f in range(PORTAL_FRAMES):
        frame = ground_img.copy()
        for i, color in enumerate(("blue", "orange")):
            body, glow = portal_frame(color, f)
            layer = Image.new("RGBA", (w, h), (0, 0, 0, 0))
            layer.paste(body, (i * PORTAL_SIZE, 0))
            frame = over(layer, frame)
            glow_layer = Image.new("RGBA", (w, h), (0, 0, 0, 0))
            glow_layer.paste(glow, (i * PORTAL_SIZE, 0))
            frame = add_glow(glow_layer, frame)
        frames.append(frame.convert("RGB"))
    # 16 frames at 0.33 frames per tick is ~48 ticks = 0.8 s per loop in game
    frames[0].save(media / "portals.gif", save_all=True, append_images=frames[1:], duration=50, loop=0)
    print(f"  {(media / 'portals.gif').relative_to(ROOT)}")
    strip = Image.new("RGBA", (64 * 4 + 24 * 3, 64), (0, 0, 0, 0))
    for i, name in enumerate(("portal-gun", "portal-blue", "portal-orange")):
        strip.alpha_composite(Image.open(GFX / "icons" / f"{name}.png").convert("RGBA"), (i * 88, 0))
    strip.alpha_composite(Image.open(GFX / "technology" / "portal-gun.png").convert("RGBA").resize((64, 64), Image.LANCZOS), (3 * 88, 0))
    save(strip, media / "icons.png")


