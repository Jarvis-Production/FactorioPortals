# --------------------------------------------------------------------------------------------- helpers

def pal(color: str) -> dict[str, np.ndarray]:
    return {k: np.array(v, dtype=np.float64) / 255.0 for k, v in PALETTES[color].items()}


def rgba(rgb: np.ndarray, alpha: np.ndarray) -> Image.Image:
    """Float RGB (H,W,3) and alpha (H,W) in 0..1 -> straight-alpha RGBA image."""
    rgb = np.clip(rgb, 0, 1)
    alpha = np.clip(alpha, 0, 1)
    rgb = np.where(alpha[..., None] > 1e-4, rgb, 0.0)
    out = np.dstack([rgb, alpha]) * 255.0
    return Image.fromarray(np.round(out).astype(np.uint8), "RGBA")


def premul(img: Image.Image) -> tuple[np.ndarray, np.ndarray]:
    a = np.asarray(img, dtype=np.float64) / 255.0
    return a[..., :3] * a[..., 3:4], a[..., 3]


def unpremul(rgb_p: np.ndarray, alpha: np.ndarray) -> Image.Image:
    alpha = np.clip(alpha, 0, 1)
    rgb = np.where(alpha[..., None] > 1e-4, rgb_p / np.maximum(alpha[..., None], 1e-4), 0.0)
    return rgba(rgb, alpha)


def over(top: Image.Image, bottom: Image.Image) -> Image.Image:
    """Normal 'over' compositing of two straight-alpha RGBA images of the same size."""
    t_rgb, t_a = premul(top)
    b_rgb, b_a = premul(bottom)
    return unpremul(t_rgb + b_rgb * (1 - t_a[..., None]), t_a + b_a * (1 - t_a))


def add_glow(glow: Image.Image, base: Image.Image) -> Image.Image:
    """What the game shows for an additive glow layer drawn over a normal layer, flattened for UI icons."""
    g_rgb, g_a = premul(glow)
    b_rgb, b_a = premul(base)
    return unpremul(np.clip(b_rgb + g_rgb, 0, 1), np.clip(b_a + g_a * 0.85, 0, 1))


def sheet(frames: list[Image.Image], line_length: int) -> Image.Image:
    w, h = frames[0].size
    rows = math.ceil(len(frames) / line_length)
    out = Image.new("RGBA", (w * line_length, h * rows), (0, 0, 0, 0))
    for i, frame in enumerate(frames):
        out.paste(frame, ((i % line_length) * w, (i // line_length) * h))
    return out


def grid(size: int) -> tuple[np.ndarray, np.ndarray]:
    y, x = np.mgrid[0:size, 0:size].astype(np.float64)
    c = (size - 1) / 2
    return x - c, y - c


def save(img: Image.Image, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    img.save(path, optimize=True)
    print(f"  {path.relative_to(ROOT)}  {img.size[0]}x{img.size[1]}")


# --------------------------------------------------------------------------------------------- portals

PORTAL_FRAMES = 16
PORTAL_SIZE = 192      # px per frame; drawn at scale 0.5 -> 3x3 tiles
PORTAL_RADIUS = 64.0   # px; the rim sits 1 tile from the centre


def portal_frame(color: str, f: int, size: int = PORTAL_SIZE, radius: float = PORTAL_RADIUS):
    """One animation frame -> (body, glow). Body is drawn normally, glow additively (and as glow at night)."""
    p = pal(color)
    dx, dy = grid(size)
    r = np.hypot(dx, dy) / radius          # 1.0 on the rim
    th = np.arctan2(dy, dx)
    phase = 2 * np.pi * f / PORTAL_FRAMES  # every periodic term below completes whole cycles over the loop
    inside = (r < 1.0).astype(np.float64)

    arms = 0.5 + 0.5 * np.cos(3 * (th + 2.8 * r) - phase)        # 3 twisted arms, turning
    flow = 0.5 + 0.5 * np.cos(2 * np.pi * 3.0 * r + phase)       # rings drifting inwards
    depth = np.clip(r, 0, 1) ** 1.6                              # 0 in the middle of the vortex, 1 at the rim

    # Body: a dark vortex that hides the ground, brightening towards the rim.
    body_rgb = p["deep"] * (1 - depth)[..., None] + p["mid"] * depth[..., None]
    body_rgb = body_rgb * (0.72 + 0.28 * flow)[..., None]
    crest = (arms ** 3) * (0.25 + 0.75 * depth)
    body_rgb = body_rgb + (p["light"] - body_rgb) * (0.55 * crest)[..., None]
    edge = np.clip((1.0 - r) * radius / 1.5 + 0.5, 0, 1)         # ~1.5 px anti-aliased edge
    body_a = edge * (0.86 + 0.1 * depth)

    # Glow: a hot rim, an inner bloom, an outer halo, bright arm crests and orbiting sparks.
    shimmer = 0.8 + 0.2 * np.cos(2 * th - phase)
    rim_core = np.exp(-(((r - 1.0) * radius) / 2.2) ** 2) * shimmer
    rim_wide = np.exp(-(((r - 1.0) * radius) / 6.0) ** 2) * 0.55
    halo = np.where(r > 1.0, np.exp(-(r - 1.0) / 0.13), 0.0) * 0.5 * np.clip((1.46 - r) / 0.12, 0, 1)
    bloom = np.exp(-(((r - 0.9) * radius) / 7.0) ** 2) * 0.3 * inside
    crests = (arms ** 12) * depth * inside * 0.5

    sparks = np.zeros_like(r)
    rng = np.random.default_rng({"blue": 11, "orange": 23}[color])
    for _ in range(12):
        laps = rng.choice([-2, -1, 1, 1, 2])                     # whole laps per loop keep it seamless
        angle = rng.uniform(0, 2 * np.pi) + 2 * np.pi * laps * f / PORTAL_FRAMES
        rad = rng.uniform(0.96, 1.18) * radius
        twinkle = 0.55 + 0.45 * np.cos(2 * np.pi * rng.integers(1, 4) * f / PORTAL_FRAMES + rng.uniform(0, 6.3))
        sx, sy = rad * np.cos(angle), rad * np.sin(angle)
        sparks += np.exp(-((dx - sx) ** 2 + (dy - sy) ** 2) / (2 * 1.6 ** 2)) * twinkle

    hot = np.clip(rim_core + sparks, 0, 1)
    glow_i = np.clip(rim_core + rim_wide + halo + bloom + crests + sparks, 0, 1)
    colored = np.clip(rim_wide + halo + bloom + crests, 0, None)
    w_hot = hot / np.maximum(hot + colored, 1e-6)
    glow_rgb = p["light"] * (1 - w_hot)[..., None] + p["hot"] * w_hot[..., None]
    w_mid = np.clip(halo / np.maximum(glow_i, 1e-6), 0, 1)
    glow_rgb = glow_rgb * (1 - w_mid)[..., None] + p["mid"] * w_mid[..., None]
    return rgba(body_rgb, body_a), rgba(glow_rgb, glow_i)


def portal_icon(color: str, size: int) -> Image.Image:
    body, glow = portal_frame(color, 0)
    flat = add_glow(glow, body)
    margin = (PORTAL_SIZE - 150) // 2
    return flat.crop((margin, margin, PORTAL_SIZE - margin, PORTAL_SIZE - margin)).resize((size, size), Image.LANCZOS)


def make_portals() -> None:
    for color in ("blue", "orange"):
        frames = [portal_frame(color, f) for f in range(PORTAL_FRAMES)]
        save(sheet([b for b, _ in frames], 4), GFX / "entity/portal" / f"portal-{color}-body.png")
        save(sheet([g for _, g in frames], 4), GFX / "entity/portal" / f"portal-{color}-glow.png")
        save(portal_icon(color, 64), GFX / "icons" / f"portal-{color}.png")


# --------------------------------------------------------------------------------------------- shots

def make_shots(w: int = 48, h: int = 128) -> None:
    """A streak pointing north (projectiles are rotated to their direction of travel); tinted in game."""
    y, x = np.mgrid[0:h, 0:w].astype(np.float64)
    cx, head = (w - 1) / 2, 34.0
    t = np.clip((y - head) / (h - 10 - head), 0, 1)              # 0 at the head, 1 at the end of the tail
    behind = (y >= head).astype(np.float64)
    blob = np.exp(-((x - cx) ** 2 + (y - head) ** 2) / (2 * 8.5 ** 2))
    tail_w = 6.5 * (1 - t) + 1.2
    tail = np.exp(-((x - cx) ** 2) / (2 * tail_w ** 2)) * (1 - t) ** 1.7 * behind
    glow = np.clip(blob + 0.75 * tail, 0, 1)
    core = np.clip(np.exp(-((x - cx) ** 2 + (y - head) ** 2) / (2 * 3.2 ** 2))
                   + 0.65 * np.exp(-((x - cx) ** 2) / (2 * 1.1 ** 2)) * (1 - t) ** 2.2 * behind, 0, 1)
    white = np.ones((h, w, 3))
    save(rgba(white, glow * 0.9), GFX / "entity/shot/shot-glow.png")
    save(rgba(white, core), GFX / "entity/shot/shot-core.png")


# --------------------------------------------------------------------------------------------- effects

EFFECT_FRAMES = 16
EFFECT_SIZE = 128


def ring_burst_frame(f: int) -> Image.Image:
    dx, dy = grid(EFFECT_SIZE)
    r, th = np.hypot(dx, dy), np.arctan2(dy, dx)
    t = f / (EFFECT_FRAMES - 1)
    radius = 6 + 52 * (1 - (1 - t) ** 2.2)
    thickness = 6.5 * (1 - t) + 1.8
    ring = np.exp(-((r - radius) / thickness) ** 2) * (1 - t) ** 1.2 * (0.72 + 0.28 * np.cos(10 * th + 1.3))
    flash = np.exp(-(r / (16 * (1 + 1.5 * t))) ** 2) * (1 - t) ** 3 * 1.1
    rays = np.exp(-((r - radius * 0.82) / (radius * 0.16 + 1)) ** 2) * (np.cos(8 * th) ** 24) * (1 - t) ** 3 * 0.5
    return rgba(np.ones((EFFECT_SIZE, EFFECT_SIZE, 3)), np.clip(ring + flash + rays, 0, 1))


def sparks_frames() -> list[Image.Image]:
    rng = np.random.default_rng(7)
    n = 30
    angles = rng.uniform(0, 2 * np.pi, n)
    speeds = rng.uniform(2.0, 4.6, n)
    lives = rng.uniform(9, 16, n)
    dx, dy = grid(EFFECT_SIZE)
    frames = []
    for f in range(EFFECT_FRAMES):
        a = np.zeros_like(dx)
        for ang, v, life in zip(angles, speeds, lives):
            if f >= life:
                continue
            k = 1 - f / life
            dist = v * f * (1 - f / (2 * life)) + 3
            ux, uy = math.cos(ang), math.sin(ang)
            length = 2.5 + 3.5 * v * k
            # distance from each pixel to the streak segment [dist - length, dist] along (ux, uy)
            along = dx * ux + dy * uy
            across = -dx * uy + dy * ux
            clamped = np.clip(along, dist - length, dist)
            d2 = (along - clamped) ** 2 + across ** 2
            a += np.exp(-d2 / (2 * 0.9 ** 2)) * k ** 1.2
        a += np.exp(-(np.hypot(dx, dy) / 10) ** 2) * max(0.0, 1 - f / 4) * 1.2
        frames.append(rgba(np.ones((EFFECT_SIZE, EFFECT_SIZE, 3)), np.clip(a, 0, 1)))
    return frames


def make_effects() -> None:
    save(sheet([ring_burst_frame(f) for f in range(EFFECT_FRAMES)], 4), GFX / "entity/effects/ring-burst.png")
    save(sheet(sparks_frames(), 4), GFX / "entity/effects/sparks.png")


