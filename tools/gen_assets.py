def lerp(a, b, t):
    return tuple(int(round(a[i] + (b[i] - a[i]) * t)) for i in range(len(a)))


def draw_gun(size: int) -> Image.Image:
    """The portal gun, muzzle up-right, on a transparent square. Drawn 4x larger and scaled down."""
    s = 4
    big = size * s
    k = big / 256.0                     # design units: a 256 x 256 canvas
    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)

    def P(points):
        return [(px * k, py * k) for px, py in points]

    def box(x0, y0, x1, y1):
        return [x0 * k, y0 * k, x1 * k, y1 * k]

    outline = (24, 26, 32, 255)
    white_hi, white_lo = (250, 251, 252, 255), (178, 184, 194, 255)
    dark, darker = (58, 62, 72, 255), (30, 32, 38, 255)
    blue = PALETTES["blue"]

    # handle
    d.polygon(P([(92, 146), (122, 146), (112, 206), (78, 206)]), fill=outline)
    d.polygon(P([(96, 148), (118, 148), (109, 202), (82, 202)]), fill=dark)
    # rear housing: a white capsule, shaded top to bottom
    d.rounded_rectangle(box(27, 93, 143, 157), radius=29 * k, fill=outline)
    ys = np.linspace(0, 1, big)[:, None, None]
    t = np.clip((ys - 96 / 256) / (58 / 256), 0, 1) ** 1.4
    grad = np.array(white_hi, dtype=np.float64) * (1 - t) + np.array(white_lo, dtype=np.float64) * t
    grad = Image.fromarray(np.broadcast_to(grad, (big, big, 4)).astype(np.uint8), "RGBA")
    mask = Image.new("L", (big, big), 0)
    ImageDraw.Draw(mask).rounded_rectangle(box(30, 96, 140, 154), radius=27 * k, fill=255)
    img.paste(grad, (0, 0), mask)
    d.rounded_rectangle(box(44, 104, 112, 112), radius=4 * k, fill=(255, 255, 255, 255))   # highlight
    d.line(P([(60, 140), (118, 140)]), fill=(150, 156, 168, 255), width=int(3 * k))         # seam
    # black collar with a glowing band
    d.rounded_rectangle(box(132, 90, 170, 160), radius=10 * k, fill=outline)
    d.rounded_rectangle(box(135, 93, 167, 157), radius=8 * k, fill=darker)
    d.rectangle(box(148, 95, 155, 155), fill=blue["mid"] + (255,))
    d.rectangle(box(150, 95, 153, 155), fill=blue["hot"] + (255,))
    # barrel
    d.rounded_rectangle(box(164, 106, 204, 144), radius=8 * k, fill=outline)
    d.rounded_rectangle(box(166, 109, 202, 141), radius=7 * k, fill=dark)
    d.line(P([(170, 115), (198, 115)]), fill=(110, 116, 130, 255), width=int(3 * k))
    # three claws around the muzzle
    d.polygon(P([(190, 104), (214, 86), (238, 92), (218, 100), (204, 114)]), fill=outline)
    d.polygon(P([(190, 146), (214, 164), (238, 158), (218, 150), (204, 136)]), fill=outline)
    d.polygon(P([(194, 107), (214, 91), (230, 94), (215, 101), (204, 111)]), fill=(84, 90, 104, 255))
    d.polygon(P([(194, 143), (214, 159), (230, 156), (215, 149), (204, 139)]), fill=(70, 74, 86, 255))

    # glowing core with a halo
    core = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    cd = ImageDraw.Draw(core)
    cx, cy = 214 * k, 125 * k
    for rad, col in ((30, blue["mid"] + (70,)), (21, blue["mid"] + (150,)), (14, blue["light"] + (255,)),
                     (8, blue["hot"] + (255,))):
        cd.ellipse([cx - rad * k, cy - rad * k, cx + rad * k, cy + rad * k], fill=col)
    core = core.filter(ImageFilter.GaussianBlur(3 * k))
    img.alpha_composite(core)

    img = img.rotate(24, resample=Image.BICUBIC, center=(big / 2, big / 2))
    # Fill the square: crop to the drawing, pad to a square with a small margin, then scale down.
    x0, y0, x1, y1 = img.getchannel("A").point(lambda a: 255 if a > 8 else 0).getbbox()
    side = int(max(x1 - x0, y1 - y0) * 1.04)
    square = Image.new("RGBA", (side, side), (0, 0, 0, 0))
    square.alpha_composite(img.crop((x0, y0, x1, y1)), ((side - (x1 - x0)) // 2, (side - (y1 - y0)) // 2))
    return square.resize((size, size), Image.LANCZOS)


